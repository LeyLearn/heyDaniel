CREATE TABLE Users (
  Id int(11) AUTO_INCREMENT PRIMARY KEY NOT NULL,
  Name LONGTEXT NOT NULL,
  Email LONGTEXT NOT NULL,
  Password LONGTEXT NOT NULL,
  Phone TINYTEXT NOT NULL,
  Address LONGTEXT NOT NULL,
  Apt LONGTEXT NOT NULL,
  ZipCode LONGTEXT NOT NULL,
  LatnLong LONGTEXT NOT NULL,
  GateCode LONGTEXT NOT NULL,
  Note LONGTEXT NOT NULL,
  Credits LONGTEXT NOT NULL,
  IsMember TINYTEXT NOT NULL,
  AppleDevice TINYTEXT NOT NULL,
  AndroidDevice TINYTEXT NOT NULL,
  WebDevice TINYTEXT NOT NULL,
  TimeRegister  TINYTEXT NOT NULL,
  TimeMembership  TINYTEXT NOT NULL,
  IsActive TINYTEXT NOT NULL
);